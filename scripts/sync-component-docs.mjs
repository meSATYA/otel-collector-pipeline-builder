import { readFile, writeFile, mkdir } from "node:fs/promises";

const source = await readFile(new URL("../app/page.tsx", import.meta.url), "utf8");
const categories = ["receivers", "processors", "exporters", "extensions", "connectors"];
const paths = { receivers: "receiver", processors: "processor", exporters: "exporter", extensions: "extension", connectors: "connector" };
const components = categories.flatMap((category) => {
  const match = source.match(new RegExp(`${category}: \\[(.*?)\\],`, "s"));
  if (!match) throw new Error(`Could not find ${category} data`);
  return [...match[1].matchAll(/"([^"]+)"/g)].map((entry) => ({ category, path: paths[category], name: entry[1] }));
});

function cleanMarkdown(markdown) {
  return markdown
    .replace(/<!--.*?-->/gs, "")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/^>\s?/gm, "")
    .replace(/^[-*+]\s+/gm, "• ")
    .replace(/^\d+\.\s+/gm, "• ")
    .replace(/<[^>]+>/g, "")
    .replace(/[`*_~]/g, "")
    .replace(/\r/g, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

const readmeOverrides = {
  dbauth: "extension/dbauth/awsiamdbauthextension",
  tailstorage: "extension/tailstorage/pebbletailstorageextension",
  storage: "extension/storage/filestorage",
};

async function fetchDoc(component) {
  const repoPath = readmeOverrides[component.name] ?? `${component.path}/${component.name}`;
  const url = `https://raw.githubusercontent.com/open-telemetry/opentelemetry-collector-contrib/main/${repoPath}/README.md`;
  const response = await fetch(url, { headers: { "User-Agent": "opentelemetry-collector-pipeline-builder" } });
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  const readme = await response.text();
  const marker = "<!-- end autogenerated section -->";
  const start = readme.indexOf(marker);
  const autogenerated = start >= 0 ? readme.slice(0, start) : "";
  const remainder = start >= 0 ? readme.slice(start + marker.length) : readme;
  const heading = remainder.search(/^##\s+/m);
  const section = heading >= 0 ? remainder.slice(0, heading) : remainder;
  const text = cleanMarkdown(section);
  const stability = [];
  const statusRows = autogenerated.split("\n");
  let inStabilityRows = false;
  for (const row of statusRows) {
    const cells = row.split("|").slice(1, -1).map((cell) => cell.trim());
    if (cells.length < 2) continue;
    if (cells[0] === "Stability") inStabilityRows = true;
    else if (inStabilityRows && cells[0] !== "") inStabilityRows = false;
    if (!inStabilityRows) continue;
    const match = cells[1].match(/\[([^\]]+)\]\s*:\s*(.+)/);
    if (!match) continue;
    for (const type of match[2].split(",").map((value) => value.trim().toLowerCase()).filter(Boolean)) {
      stability.push({ level: match[1].toLowerCase(), type });
    }
  }
  // Connectors describe both sides in a generated Supported Pipeline Types table.
  const connectorTable = autogenerated.match(/## Supported Pipeline Types([\s\S]*?)(?:<!-- end autogenerated section -->|$)/i)?.[1] ?? "";
  for (const row of connectorTable.split("\n")) {
    const cells = row.split("|").slice(1, -1).map((cell) => cell.trim());
    if (cells.length !== 3 || !/^\[(alpha|beta|stable|development)\]$/i.test(cells[2])) continue;
    for (const type of cells.slice(0, 2).map((value) => value.toLowerCase()).filter(Boolean)) {
      stability.push({ level: cells[2].slice(1, -1).toLowerCase(), type });
    }
  }
  const uniqueStability = [...new Map(stability.map((entry) => [`${entry.level}:${entry.type}`, entry])).values()];
  const pipelineTypes = [...new Set(uniqueStability.map((entry) => entry.type))];
  const description = text
    .replace(/Supported pipeline types?:\s*[^\n]+/i, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return [component.name, { description: description || `See the official ${component.name} documentation for details.`, pipelineTypes, stability: uniqueStability, docsUrl: `https://github.com/open-telemetry/opentelemetry-collector-contrib/blob/main/${repoPath}/README.md`, repoPath }];
}

const entries = [];
const failures = [];
for (let index = 0; index < components.length; index += 12) {
  const batch = components.slice(index, index + 12);
  const results = await Promise.all(batch.map(async (component) => {
    try { return await fetchDoc(component); }
    catch (error) { failures.push(`${component.name}: ${error.message}`); return null; }
  }));
  entries.push(...results.filter(Boolean));
}

const expectedFailures = failures.filter((failure) => !failure.startsWith("internal:"));
if (expectedFailures.length) throw new Error(`README sync failed:\n${expectedFailures.join("\n")}`);
const output = `// Generated from component README files by scripts/sync-component-docs.mjs.\n` +
  `// Do not edit manually. Run npm run sync:docs to refresh from main.\n` +
  `export type ComponentDoc = { description: string; pipelineTypes: string[]; stability: { level: string; type: string }[]; docsUrl: string; repoPath: string };\n` +
  `export const componentDocs: Record<string, ComponentDoc> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`;
await mkdir(new URL("../app", import.meta.url), { recursive: true });
await writeFile(new URL("../app/component-docs.ts", import.meta.url), output);
console.log(`Synced ${entries.length} component README files.`);
