import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { resolve } from "node:path";

const packageRoot = resolve("work/simple-icons/package");
if (!existsSync(packageRoot)) throw new Error("Extract the Simple Icons package under work/simple-icons/package first.");
const source = await readFile("app/page.tsx", "utf8");
const categories = ["receivers", "processors", "exporters", "extensions", "connectors"];
const components = categories.flatMap((category) => {
  const match = source.match(new RegExp(`${category}: \\[(.*?)\\],`, "s"));
  return [...match[1].matchAll(/"([^"]+)"/g)].map((entry) => entry[1]);
});

// Ordered, conservative matches. A logo is assigned only when a component name
// clearly refers to the corresponding product, project, platform, or vendor.
const rules = [
  [/^alibaba/, "alibabacloud"], [/^googlecloud|^gcp/, "googlecloud"],
  [/apachespark/, "apachespark"], [/apache/, "apache"],
  [/cloudflare/, "cloudflare"], [/cloudfoundry/, "cloudfoundry"], [/couchdb/, "apachecouchdb"],
  [/cassandra/, "apachecassandra"], [/clickhouse/, "clickhouse"], [/datadog/, "datadog"],
  [/docker/, "docker"], [/elasticsearch/, "elasticsearch"], [/envoy/, "envoyproxy"],
  [/flink/, "apacheflink"], [/fluent/, "fluentd"], [/github/, "github"], [/gitlab/, "gitlab"],
  [/googlecloudspanner/, "googlecloudspanner"], [/googlecloud|googlemanaged/, "googlecloud"],
  [/grafana|faro|loki/, "grafana"], [/huawei/, "huawei"], [/influxdb/, "influxdb"],
  [/jaeger/, "jaeger"], [/kafka/, "apachekafka"], [/k8s|kubelet/, "kubernetes"],
  [/mongodb/, "mongodb"], [/mysql/, "mysql"], [/nginx/, "nginx"], [/opensearch/, "opensearch"],
  [/otelarrow/, "apachearrow"], [/otlp|opentelemetry/, "opentelemetry"], [/podman/, "podman"],
  [/postgresql/, "postgresql"], [/prometheus/, "prometheus"], [/pulsar/, "apachepulsar"],
  [/rabbitmq/, "rabbitmq"], [/redis/, "redis"], [/sentry/, "sentry"], [/snowflake/, "snowflake"],
  [/splunk/, "splunk"], [/sumologic/, "sumologic"], [/vcenter/, "vmware"], [/cisco/, "cisco"],
  [/windows/, "windows"], [/macos/, "apple"], [/systemd/, "systemd"], [/journald/, "linux"],
];

const catalog = JSON.parse(await readFile(`${packageRoot}/data/simple-icons.json`, "utf8"));
const bySlug = new Map(catalog.map((icon) => [icon.slug, icon]));
const mapping = {};
await mkdir("public/logos", { recursive: true });
for (const component of components) {
  const cloudPrefix = [
    [/^aws/, { slug: "cloud-aws", title: "Amazon Web Services", color: "#FF9900" }],
    [/^azure/, { slug: "cloud-azure", title: "Microsoft Azure", color: "#0089D6" }],
    [/^oracle/, { slug: "cloud-oracle", title: "Oracle Cloud", color: "#F80000" }],
  ].find(([pattern]) => pattern.test(component));
  if (cloudPrefix) {
    mapping[component] = cloudPrefix[1];
    continue;
  }
  const match = rules.find(([pattern]) => pattern.test(component));
  if (!match) continue;
  const slug = match[1];
  const icon = bySlug.get(slug);
  const sourceIcon = `${packageRoot}/icons/${slug}.svg`;
  if (!icon || !existsSync(sourceIcon)) continue;
  await copyFile(sourceIcon, `public/logos/${slug}.svg`);
  mapping[component] = { slug, title: icon.title, color: `#${icon.hex}` };
}
await copyFile(`${packageRoot}/LICENSE.md`, "public/logos/SIMPLE-ICONS-LICENSE.md");
await copyFile(`${packageRoot}/DISCLAIMER.md`, "public/logos/SIMPLE-ICONS-DISCLAIMER.md");
await writeFile("app/component-logos.ts", `// Generated by scripts/sync-brand-logos.mjs.\nexport type ComponentLogo = { slug: string; title: string; color: string };\nexport const componentLogos: Record<string, ComponentLogo> = ${JSON.stringify(mapping, null, 2)};\n`);
console.log(`Assigned verified brand marks to ${Object.keys(mapping).length} components using ${new Set(Object.values(mapping).map((item) => item.slug)).size} local SVG assets.`);
